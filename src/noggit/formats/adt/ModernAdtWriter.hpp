// Native modern ADT writer (issue: "Implement native modern ADT writer").
//
// Design goals, straight from the issue scope:
//
//  * Version-aware serialization instead of replacing the legacy writer.
//    All format decisions live in an AdtFormatProfile; the first (and for
//    now only) target is the Shadowlands 9.2.7 split ADT, MVER 18. Later
//    client generations add a profile (and, where needed, overrides) rather
//    than editing the writer.
//  * Native container assembly. The ROOT part - MVER, MHDR, MCIN and the
//    256 MCNKs with their editor-owned subchunks - is generated by this
//    writer, including the bookkeeping the legacy conversion path left
//    stale: MCIN offsets/sizes are recomputed against the emitted layout,
//    MHDR offsets are re-derived (self-calibrated against the original
//    file so the retail offset convention is preserved whatever it is),
//    and MCNK header subchunk offsets are recomputed for every subchunk
//    the writer re-lays out.
//  * Safe preservation. Every top-level chunk the writer does not own
//    (MTXP and friends) and every MCNK subchunk outside the owned set is
//    copied byte-for-byte from the original file, in original order.
//  * Validation before writing. validatePart() structurally checks an
//    assembled part (chunk walk, counts, sizes, MCIN/MHDR consistency,
//    header offset targets) and is run before anything touches disk, so a
//    corrupt tile is never saved silently.
//
// Payload sourcing is explicitly staged: rootInputFromLegacy() extracts the
// editor-owned chunk payloads from Noggit's canonical legacy serialization
// (the byte-level chunk formats - MCVT/MCNR/MCCV/MCSH/MCSE - are identical
// between WotLK and 9.2.7, only the container differs). NativeRootInput is
// source-agnostic, so a later increment can fill it directly from MapChunk
// state and drop the legacy pass entirely without touching this writer.

#pragma once

#include <noggit/MapHeaders.h>

#include <array>
#include <cstdint>
#include <optional>
#include <stdexcept>
#include <string>
#include <vector>

namespace Noggit::Formats::ADT
{
  // Version-aware format profile. Adding support for a later client
  // generation means adding a profile, not editing the write path.
  struct AdtFormatProfile
  {
    char const* name = "ADT v18 (Shadowlands 9.2.7)";
    //! Client build this profile writes for. The writer stamps MVER with
    //! `mver` and assumes this build's chunk shapes, so a project whose CASC
    //! comes from a different build produces a file wearing one version's
    //! version stamp around another version's contents and asset ids.
    char const* target_build = "9.2.7";
    std::uint32_t mver = 18;
    std::size_t mcnk_count = 256;
    std::size_t chunk_header_size = sizeof(MapChunkHeader); // ROOT MCNKs carry one
    std::size_t heightmap_values = 145;                     // 9*9 + 8*8 vertices
    std::size_t mcin_entry_size = sizeof(ENTRY_MCIN);
    bool root_mcnk_has_header = true;
    bool supports_high_res_holes = true;
  };

  // The current format target: Shadowlands 9.2.7.
  AdtFormatProfile const& adt_profile_v18();

  // Editor-owned payload of one ROOT MCNK. An empty optional means "the
  // editor does not own / did not produce this subchunk" and the original
  // file's chunk (if any) is preserved; a present-but-empty vector is a
  // legitimate zero-length chunk.
  struct ModernChunkPayload
  {
    std::optional<std::vector<std::uint8_t>> header; // sizeof(MapChunkHeader)
    std::optional<std::vector<std::uint8_t>> mcvt;
    std::optional<std::vector<std::uint8_t>> mcnr;
    std::optional<std::vector<std::uint8_t>> mccv;
    std::optional<std::vector<std::uint8_t>> mcsh;
    std::optional<std::vector<std::uint8_t>> mcse;
  };

  struct NativeRootInput
  {
    std::uint32_t mhdr_flags = 0;
    std::array<ModernChunkPayload, 256> chunks;
    bool has_mh2o = false;
    std::vector<std::uint8_t> mh2o_payload; // chunk payload without header
    bool has_mfbo = false;
    std::vector<std::uint8_t> mfbo_payload;
  };

  // What a part is expected to contain, for validation.
  enum class AdtPartExpectation
  {
    Generic, // chunk walk only (OBJ1, LOD, ...)
    Root,    // MVER/MHDR/MCIN + 256 MCNKs + bookkeeping consistency
    Texture, // 256 MCNKs with MCLY/MCAL shapes
    Object   // 256 MCNKs with MDDF/MODF/MCRD/MCRW consistency
  };

  // Structural failure inside the writer (bad original file, writer defect).
  // Callers may fall back to another save path on this.
  class ModernAdtWriterError : public std::runtime_error
  {
  public:
    using std::runtime_error::runtime_error;
  };

  // Validation rejected assembled bytes. Callers must NOT write them and
  // must NOT fall back to a path that would write the same data unvalidated.
  class ModernAdtValidationError : public ModernAdtWriterError
  {
  public:
    using ModernAdtWriterError::ModernAdtWriterError;
  };

  //! Regeneration of the OBJ1 LOD placement chunks against the merged OBJ0
  //! placement lists.
  //!
  //! Retail OBJ1 layouts vary per tile: the doodad side (MLDD/MLDX with the
  //! optional companions MLDL, MDLI and MLDB) can exist without the WMO side
  //! (MLMD/MLMX with the optional companions MLMB and MWDR/MWDS) and vice
  //! versa, and MLDL only ships when a doodad carries the liquid-height flag.
  //! Requiring every chunk at once refused the merge for 169 azeroth tiles in
  //! one session ("OBJ1 has an unsupported LOD placement layout"), so nothing
  //! of those tiles' edits reached disk.
  //!
  //! The rewrite regenerates the sides that exist and keeps the per-entry
  //! companion chunks (MLDB per MLDD, MLMB/MWDR per MLMD) in lockstep with
  //! the lists they annotate: a companion array whose count disagrees with
  //! its list is an out-of-bounds read for the client when it streams the
  //! tile's LOD objects. Placements the editor added stay out of the LOD
  //! lists (they render normally up close and gain LOD representation when
  //! the lists are next regenerated from the game data), placements the
  //! editor deleted leave the lists, and survivors keep their retail band
  //! membership, flags and companion bytes with their transforms updated.
  struct Obj1LodRewrite
  {
    //! The OBJ1 to write: the regenerated one, or the untouched input when
    //! the layout is passed through.
    std::vector<std::uint8_t> bytes;
    //! True when LOD chunks were regenerated.
    bool rewritten = false;
    //! Non-empty when OBJ1 carries LOD chunks in a layout this writer cannot
    //! regenerate. bytes is then the untouched input: internally consistent
    //! (every companion still matches its list) but possibly stale relative
    //! to edited placements, which shows as distant LOD objects lagging the
    //! edit rather than as a broken tile. Callers should surface it.
    std::string reason;
  };

  [[nodiscard]] Obj1LodRewrite rewriteObj1Lod(
      std::vector<std::uint8_t> const& obj1,
      std::vector<std::uint8_t> const& mddf_payload,
      std::vector<std::uint8_t> const& modf_payload);

  //! Keeps OBJ0's per-WMO companion chunks in step with a rebuilt MODF.
  //!
  //! MLMB (8.2+) carries one byte per MODF placement and MWDR/MWDS (9.0+)
  //! one {begin,end} range per MODF into the shared MWDS pool. A merge that
  //! replaces MODF but copies these arrays byte-for-byte leaves counts and
  //! order disagreeing with the placements they annotate - the same
  //! out-of-bounds class the OBJ1 companions have. Survivors carry their
  //! retail bytes by (nameID, uniqueID); editor-added placements get the
  //! most common retail MLMB class and an empty MWDR range. An array whose
  //! size does not match the retail MODF count contradicts the documented
  //! layout, so it is dropped (the client falls back to its defaults) and
  //! reported rather than guessed at.
  struct Obj0CompanionRewrite
  {
    std::vector<std::uint8_t> bytes;
    //! Editor-added WMO placements that were given default companion bytes.
    std::size_t defaults_used = 0;
    //! FileDataID of the first placement that got defaults (0 when none did).
    std::uint32_t first_default_fdid = 0;
    //! Non-empty when a companion chunk was dropped as contradicting the
    //! documented layout; callers should surface it.
    std::string note;
  };

  [[nodiscard]] Obj0CompanionRewrite rewriteObj0Companions(
      std::vector<std::uint8_t> const& obj0,
      std::vector<std::uint8_t> const& original_obj0);

  //! Which object part validateObjectCompanions should read the bytes as.
  enum class ObjectPartKind
  {
    Obj0, //! MDDF/MODF placements with MLMB/MWDR/MWDS companions
    Obj1, //! MLDD/MLDX and MLMD/MLMX LOD lists with MLDB/MLMB/MWDR companions
  };

  //! Crash-risk audit for the per-entry companion chunks of an object part:
  //! MLDB/MLMB/MWDR and the extent lists are read by the client in lockstep
  //! with the placement lists they annotate, so a size that disagrees with
  //! the list count is an out-of-bounds read while the tile streams in - the
  //! access-violation class of the 2026-10-24 field crash. Files written by
  //! builds before the companion fixes still sit in project folders and pass
  //! structural validation; this audit names them. Returns one human-readable
  //! problem per mismatch (empty = consistent). Absent companions are legal
  //! and stay unreported; so are companions whose list is absent - without
  //! the list the client never reads them.
  [[nodiscard]] std::vector<std::string> validateObjectCompanions(
      std::vector<std::uint8_t> const& part, ObjectPartKind kind);

  class ModernAdtWriter
  {
  public:
    // Transitional payload source: extracts the editor-owned ROOT data from
    // Noggit's canonical legacy serialization (handles the 13 padding bytes
    // the legacy serializer emits after MCNR). Throws ModernAdtWriterError
    // when the legacy buffer is malformed.
    [[nodiscard]] static NativeRootInput rootInputFromLegacy(
        AdtFormatProfile const& profile,
        std::vector<std::uint8_t> const& legacy_adt);

    // Assembles the modern ROOT part natively. Original top-level chunk order
    // is kept; owned chunks are regenerated, everything else is preserved.
    // The result passes validatePart(Root) or the function throws
    // ModernAdtWriterError (nothing is returned unvalidated).
    [[nodiscard]] static std::vector<std::uint8_t> writeRoot(
        AdtFormatProfile const& profile,
        std::vector<std::uint8_t> const& original_root,
        NativeRootInput const& input);

    // Recomputes MCIN entries and the MHDR mcin/mh2o/mfbo offsets of an
    // already-assembled ROOT part against its actual layout, preserving each
    // MCIN entry's flags/asyncID and the file's MHDR offset basis. Used to
    // repair the conversion path's stale bookkeeping. Throws
    // ModernAdtWriterError on malformed input.
    static void refreshRootBookkeeping(
        AdtFormatProfile const& profile,
        std::vector<std::uint8_t>& root);

    // Structural validation of one part. Returns the list of problems; an
    // empty list means the part is well-formed.
    [[nodiscard]] static std::vector<std::string> validatePart(
        AdtFormatProfile const& profile,
        std::vector<std::uint8_t> const& bytes,
        AdtPartExpectation expectation);

    // validatePart, but throws ModernAdtValidationError listing every problem.
    static void validatePartOrThrow(
        AdtFormatProfile const& profile,
        std::vector<std::uint8_t> const& bytes,
        AdtPartExpectation expectation,
        char const* part_label);
  };
}
